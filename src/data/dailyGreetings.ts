/**
 * Вычисляет динамическое приветствие для Анны на основе времени суток и дня недели (Europe/Samara).
 */
export function getDynamicGreeting(customTime?: {
  dayOfWeekRu: string;
  hour: number;
  year: number;
  systemDate: Date;
}): string {
  const now = customTime?.systemDate || new Date();
  const hour = customTime ? customTime.hour : now.getHours();
  const day = (customTime?.dayOfWeekRu || '').toLowerCase();
  const year = customTime ? customTime.year : now.getFullYear();

  // Вычисляем день года для равномерной ротации фраз
  const startOfYear = new Date(year, 0, 1);
  const diffMs = now.getTime() - startOfYear.getTime();
  const dayOfYear = Math.max(0, Math.floor(diffMs / 86400000));

  let pool: string[];
  if (day === 'понедельник') {
    pool = DAILY_GREETINGS.monday;
  } else if (day === 'пятница') {
    pool = DAILY_GREETINGS.friday;
  } else if (day === 'суббота' || day === 'воскресенье') {
    pool = DAILY_GREETINGS.weekend;
  } else if (hour >= 5 && hour < 12) {
    pool = DAILY_GREETINGS.morning;
  } else if (hour >= 12 && hour < 18) {
    pool = DAILY_GREETINGS.afternoon;
  } else {
    pool = DAILY_GREETINGS.evening;
  }

  const index = dayOfYear % pool.length;
  return pool[index] || pool[0];
}

