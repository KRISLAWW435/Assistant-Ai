export const DEFAULT_FALLBACK_LETTER = "Анна, сегодня отличный день, чтобы начать что-то новое! 🌸";

/**
 * Возвращает порядковый номер дня в текущем году (0-365).
 */
export function getDayOfYear(date: Date = new Date()): number {
  const start = new Date(date.getFullYear(), 0, 0);
  const diff =
    date.getTime() -
    start.getTime() +
    (start.getTimezoneOffset() - date.getTimezoneOffset()) * 60 * 1000;
  const oneDay = 1000 * 60 * 60 * 24;
  return Math.max(0, Math.floor(diff / oneDay));
}

/**
 * Выбирает письмо дня с защитой от сбоев и выводом отладки в консоль.
 */
export function getDailyLetterForToday(date: Date = new Date()): {
  text: string;
  dayIndex: number;
  totalCount: number;
} {
  const totalCount = DAILY_LETTERS.length;
  if (!totalCount) {
    console.warn("[Письмо дня] Внимание: массив фраз пуст, применена фраза-заглушка.");
    return {
      text: DEFAULT_FALLBACK_LETTER,
      dayIndex: 0,
      totalCount: 0,
    };
  }

  const dayOfYear = getDayOfYear(date);
  const dayIndex = dayOfYear % totalCount;
  const text = DAILY_LETTERS[dayIndex] || DEFAULT_FALLBACK_LETTER;

  try {
    console.log(
      `[Письмо дня] Всего фраз в массиве: ${totalCount} | Сегодня выбрана фраза (день #${dayOfYear}, индекс ${dayIndex}): "${text.slice(0, 40)}..."`
    );
  } catch {
    // ignore console restrictions
  }

  return {
    text,
    dayIndex,
    totalCount,
  };
}
