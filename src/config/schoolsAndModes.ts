export function getAgentModeConfig(
  mode: AgentMode,
  schoolId: SchoolId = 'all'
): AgentModeConfig {
  const base = AGENT_MODES[mode];
  if (!base) return AGENT_MODES.marketer;

  if (schoolId === 'all') {
    return {
      ...base,
      description:
        BOTH_SCHOOLS_SPECIALIST_DESCRIPTIONS[mode] || base.description,
      quickPrompts: BOTH_SCHOOLS_QUICK_PROMPTS[mode] || base.quickPrompts,
    };
  }

  return base;
}

export function getAgentModeList(schoolId: SchoolId = 'all'): AgentModeConfig[] {
  return [
    getAgentModeConfig('marketer', schoolId),
    getAgentModeConfig('manager', schoolId),
    getAgentModeConfig('methodist', schoolId),
    getAgentModeConfig('analyst', schoolId),
    getAgentModeConfig('designer', schoolId),
  ];
}

export const AGENT_MODE_LIST: AgentModeConfig[] = [
  AGENT_MODES.marketer,
  AGENT_MODES.manager,
  AGENT_MODES.methodist,
  AGENT_MODES.analyst,
  AGENT_MODES.designer,
];
